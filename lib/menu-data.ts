export type DietaryType = "vegan" | "veg" | "non-veg";

export function getItemDietaryType(item: MenuItem, categoryId?: string): DietaryType | null {
  if (categoryId === "cocktails" || categoryId === "weine") {
    return null;
  }
  if (item.isVegan) return "vegan";
  if (item.isVeg) return "veg";
  return "non-veg";
}

